import { PATHS } from "../paths";
import type { CreateInstallModule, ThemeTokens, Variant } from "../types";
import { installFile, writeText } from "../utils";

function buildOhMyZshTheme(variant: Variant): string {
	return `# Generated by packages/theming/create/apps/oh-my-zsh.ts
function gtheme_machine_color() {
  local color="#101010"
  local config="$HOME/.dotfiles/machine.json"

  if [[ -r "$config" ]]; then
    color=$(command awk -F'"' '$2 == "colorHex" { print $4; exit }' "$config" 2>/dev/null)
  fi

  case "$color" in
    [#][[:xdigit:]][[:xdigit:]][[:xdigit:]][[:xdigit:]][[:xdigit:]][[:xdigit:]]) ;;
    *) color="#101010" ;;
  esac
  print -nr -- "$color"
}

local machine_color=$(command awk -F'"' '$2 == "color" { print $4; exit }' "$HOME/.dotfiles/machine.json" 2>/dev/null)
local user_bg="$(gtheme_machine_color)"
local user_fg='#000000'
[[ "$machine_color" == black || -z "$machine_color" ]] && user_fg='#FFFFFF'
local path_bg="${variant.foregroundMuted}"
local path_fg='#FFFFFF'
local muted_color="${variant.foregroundMuted}"
local prompt_color="${variant.foregroundMuted}"

function prompt_context_line() {
  print -nr -- "%K{\${user_bg}}%F{\${user_fg}} ⌘ %m %k%f%K{\${path_bg}}%F{\${path_fg}} %~ %k%f"
}

function parse_git_branch() {
  git symbolic-ref --short HEAD 2>/dev/null || git rev-parse --short HEAD 2>/dev/null
}

function prompt_git_line() {
  local folder branch git_line
  local -i ahead behind
  folder="\${PWD:t}"
  branch=$(parse_git_branch)
  git_line="\${folder}"

  if [[ -n "$branch" ]]; then
    ahead=0
    behind=0
    local counts
    local -a counts_parts
    counts=$(git rev-list --left-right --count @{upstream}...HEAD 2>/dev/null)
    if [[ -n "$counts" ]]; then
      counts_parts=(\${=counts})
      [[ \${counts_parts[1]} == <-> ]] && behind=\${counts_parts[1]}
      [[ \${counts_parts[2]} == <-> ]] && ahead=\${counts_parts[2]}
    fi

    git_line+=" on \${branch}"
    (( ahead > 0 )) && git_line+=" ↑\${ahead}"
    (( behind > 0 )) && git_line+=" ↓\${behind}"
  fi

  print -nr -- "$git_line"
}

function prompt_input_line() {
  print -nr -- "%F{\${path_fg}}❯%f"
}

function prompt_system_stats() {
  [[ "$OSTYPE" == linux* && -x /usr/local/bin/xfce-system-stats ]] || return
  print -n -- "%F{\${muted_color}}%{\\e[73m%}$(/usr/local/bin/xfce-system-stats --prompt)%{\\e[75m%}%f"
}

PROMPT='$(prompt_context_line)\n$(prompt_git_line)\n$(prompt_input_line) '
RPROMPT='$(prompt_system_stats)'
`;
}

export const ohMyZshApp: CreateInstallModule = {
	appName: "oh-my-zsh",
	async create(tokens: ThemeTokens) {
		const dark = buildOhMyZshTheme(tokens.variants.dark);
		const light = buildOhMyZshTheme(tokens.variants.light);

		await writeText(PATHS.output["oh-my-zsh"].dark, dark);
		await writeText(PATHS.output["oh-my-zsh"].light, light);

		return [PATHS.output["oh-my-zsh"].dark, PATHS.output["oh-my-zsh"].light];
	},
	async install() {
		await installFile(
			PATHS.output["oh-my-zsh"].dark,
			PATHS.install["oh-my-zsh"].dark,
		);
		await installFile(
			PATHS.output["oh-my-zsh"].light,
			PATHS.install["oh-my-zsh"].light,
		);
		return [PATHS.install["oh-my-zsh"].dark, PATHS.install["oh-my-zsh"].light];
	},
};
